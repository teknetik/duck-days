#!/usr/bin/env node
/**
 * Measures the generated clips and writes public/audio/manifest.json, which is
 * what the game reads. Run after generate.mjs. Needs ffmpeg on the PATH.
 *
 * For every clip: length, RMS and peak level (the game sets playback gain from
 * these, so a regenerated clip lands at the same loudness). For one-shots it
 * also finds where the sound actually is: the syllables of each quack (the
 * bill opens in time with them), the separate strokes inside the paddling
 * recording, and the trimmed extent of each splash.
 */
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const audioRoot = join(root, 'public/audio');
const SR = 44100;

function decode(path) {
  const raw = execFileSync(
    'ffmpeg',
    ['-v', 'error', '-i', path, '-f', 'f32le', '-ac', '1', '-ar', String(SR), '-'],
    { maxBuffer: 1 << 28 }
  );
  return new Float32Array(raw.buffer, raw.byteOffset, raw.byteLength / 4);
}

const db = (v) => (v > 1e-9 ? 20 * Math.log10(v) : -120);
const round = (v, p = 3) => Math.round(v * 10 ** p) / 10 ** p;

function levels(x) {
  let sum = 0;
  let peak = 0;
  for (let i = 0; i < x.length; i++) {
    sum += x[i] * x[i];
    const a = Math.abs(x[i]);
    if (a > peak) peak = a;
  }
  return { rmsDb: round(db(Math.sqrt(sum / x.length)), 1), peakDb: round(db(peak), 1) };
}

/** RMS envelope in `win`-second hops. */
function envelope(x, win) {
  const hop = Math.round(SR * win);
  const out = new Float32Array(Math.floor(x.length / hop));
  for (let i = 0; i < out.length; i++) {
    let s = 0;
    for (let k = 0; k < hop; k++) s += x[i * hop + k] ** 2;
    out[i] = Math.sqrt(s / hop);
  }
  return out;
}

/** Stretches of sound separated by at least `minGap` of quiet (relative to the clip's peak). */
function segments(x, { threshDb = -30, minGap = 0.06, minLen = 0.04, win = 0.01 } = {}) {
  const env = envelope(x, win);
  let peak = 0;
  for (const v of env) peak = Math.max(peak, v);
  const gate = peak * 10 ** (threshDb / 20);
  const out = [];
  let start = -1;
  let lastOn = 0;
  for (let i = 0; i <= env.length; i++) {
    const t = i * win;
    const on = i < env.length && env[i] > gate;
    if (on) {
      if (start < 0) start = t;
      lastOn = t + win;
    } else if (start >= 0 && (t - lastOn >= minGap || i === env.length)) {
      if (lastOn - start >= minLen) out.push({ start: round(start), duration: round(lastOn - start) });
      start = -1;
    }
  }
  return out;
}

/** Share of energy per band, by a plain radix-2 FFT over Hann windows. */
function bands(x) {
  const n = 8192;
  const edges = [0, 150, 500, 1500, 4000, 9000, SR / 2];
  const acc = new Float64Array(edges.length - 1);
  const re = new Float64Array(n);
  const im = new Float64Array(n);
  for (let s = 0; s + n <= x.length; s += n) {
    for (let i = 0; i < n; i++) {
      re[i] = x[s + i] * (0.5 - 0.5 * Math.cos((2 * Math.PI * i) / n));
      im[i] = 0;
    }
    for (let i = 1, j = 0; i < n; i++) {
      let bit = n >> 1;
      for (; j & bit; bit >>= 1) j ^= bit;
      j ^= bit;
      if (i < j) {
        [re[i], re[j]] = [re[j], re[i]];
        [im[i], im[j]] = [im[j], im[i]];
      }
    }
    for (let len = 2; len <= n; len <<= 1) {
      const ang = (-2 * Math.PI) / len;
      const wr = Math.cos(ang);
      const wi = Math.sin(ang);
      for (let i = 0; i < n; i += len) {
        let cr = 1;
        let ci = 0;
        for (let k = 0; k < len / 2; k++) {
          const a = i + k;
          const b = a + len / 2;
          const vr = re[b] * cr - im[b] * ci;
          const vi = re[b] * ci + im[b] * cr;
          re[b] = re[a] - vr;
          im[b] = im[a] - vi;
          re[a] += vr;
          im[a] += vi;
          const nr = cr * wr - ci * wi;
          ci = cr * wi + ci * wr;
          cr = nr;
        }
      }
    }
    for (let i = 0; i < n / 2; i++) {
      const f = (i * SR) / n;
      const e = re[i] * re[i] + im[i] * im[i];
      for (let b = 0; b < acc.length; b++) if (f >= edges[b] && f < edges[b + 1]) acc[b] += e;
    }
  }
  const total = acc.reduce((a, b) => a + b, 0) || 1;
  return Object.fromEntries(
    [...acc].map((e, b) => [`${edges[b]}-${Math.round(edges[b + 1])}Hz`, round((100 * e) / total, 1)])
  );
}

const spec = JSON.parse(await readFile(join(root, 'tools/audio/clips.json'), 'utf8'));
const manifest = {
  source: `ElevenLabs sound effects (${spec.model})`,
  note: 'Generated by tools/audio/generate.mjs, measured by tools/audio/build-manifest.mjs.',
  clips: {},
};
const report = {};

for (const clip of spec.clips) {
  const path = join(audioRoot, clip.file);
  if (!existsSync(path)) continue;
  const x = decode(path);
  const entry = {
    file: clip.file,
    seconds: round(x.length / SR),
    loop: clip.loop,
    ...levels(x),
  };
  if (!clip.loop) {
    const quack = clip.id.startsWith('quack');
    const parts = segments(x, quack ? { threshDb: -24, minGap: 0.05 } : { threshDb: -30, minGap: 0.09 });
    if (parts.length) {
      // Where the sound really starts and ends, so playback has no dead air.
      const first = parts[0].start;
      const last = parts[parts.length - 1];
      entry.trim = [round(Math.max(0, first - 0.01)), round(Math.min(x.length / SR, last.start + last.duration + 0.08))];
    }
    if (quack) entry.syllables = parts;
    if (clip.id === 'paddle' || clip.id === 'bubbles') {
      entry.slices = parts
        .filter((p) => p.duration >= 0.08)
        .map((p) => {
          const a = Math.round(Math.max(0, p.start - 0.01) * SR);
          const b = Math.min(x.length, Math.round((p.start + p.duration + 0.05) * SR));
          return { start: round(a / SR), duration: round((b - a) / SR), ...levels(x.subarray(a, b)) };
        });
    }
  }
  manifest.clips[clip.id] = entry;
  report[clip.id] = { ...entry, bands: bands(x) };
}

await writeFile(join(audioRoot, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(JSON.stringify(report, null, 1));
